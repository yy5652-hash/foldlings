// Turns the Lucide icons the game uses into plain SVG path strings, so canvas
// code can draw them with Path2D. Run: node scripts/ui-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const ICONS = {
  undo: 'undo-2',
  restart: 'rotate-ccw',
  hint: 'lightbulb',
  next: 'arrow-right',
  daily: 'sun',
  recenter: 'locate-fixed',
  sound: 'volume-2',
  mute: 'volume-x',
  back: 'chevron-left',
  menu: 'layout-panel-top',
  close: 'x',
  album: 'book-open',
  settings: 'sliders-horizontal',
  levels: 'layout-grid',
  save: 'check',
  plus: 'plus',
  minus: 'minus',
  star: 'star',
  lock: 'lock',
  move: 'move',
  sparkles: 'sparkles',
  share: 'share-2',
  hand: 'hand',
  paper: 'file',
};

const num = (s, name) => Number(new RegExp(`\\b${name}="([^"]*)"`).exec(s)?.[1] ?? 0);

function toPath(tag, attrs) {
  switch (tag) {
    case 'path':
      return /\bd="([^"]*)"/.exec(attrs)[1];
    case 'circle': {
      const [cx, cy, r] = [num(attrs, 'cx'), num(attrs, 'cy'), num(attrs, 'r')];
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;
    }
    case 'rect': {
      const [x, y, w, h] = [num(attrs, 'x'), num(attrs, 'y'), num(attrs, 'width'), num(attrs, 'height')];
      const r = Math.min(num(attrs, 'rx'), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return (
        `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}` +
        `h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`
      );
    }
    case 'line':
      return `M${num(attrs, 'x1')} ${num(attrs, 'y1')}L${num(attrs, 'x2')} ${num(attrs, 'y2')}`;
    case 'polyline':
    case 'polygon': {
      const pts = /\bpoints="([^"]*)"/.exec(attrs)[1].trim();
      return `M${pts}${tag === 'polygon' ? 'Z' : ''}`;
    }
    default:
      throw new Error(`Unhandled SVG tag ${tag}`);
  }
}

let out =
  '// Generated by scripts/ui-icons.mjs from lucide-static (ISC licence, lucide.dev).\n' +
  '// Each icon is one or more SVG path strings on a 24 by 24 grid, stroked.\n\n' +
  'export const ICON_PATHS = {\n';
for (const [key, file] of Object.entries(ICONS)) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${file}.svg`, 'utf8');
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1);
  const paths = [...body.matchAll(/<(path|circle|rect|line|polyline|polygon)\b([^>]*)\/?>/g)].map((m) =>
    toPath(m[1], m[2]),
  );
  out += `  ${key}: ${JSON.stringify(paths)},\n`;
}
out += '} as const;\n\nexport type IconKind = keyof typeof ICON_PATHS;\n';
writeFileSync('src/game/icon-paths.ts', out);
console.log(`Wrote ${Object.keys(ICONS).length} icons`);
