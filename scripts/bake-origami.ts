import { registerHooks } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';

// Source imports use .js for the app; Node's type stripper needs their .ts files.
registerHooks({ resolve(specifier, context, next) {
  if (specifier.endsWith('.js') && context.parentURL?.includes('/game/origami/')) return next(specifier.slice(0, -3) + '.ts', context);
  return next(specifier, context);
} });
const { bake, patterns } = await import('../src/game/origami/bake.ts');
const { runtimeData } = await import('../src/game/origami/data.ts');
const results = [];
for (const pattern of patterns) {
  const definition = await pattern(), data = bake(definition);
  console.log(JSON.stringify({ kind: definition.kind, stages: data.stages, ...data.report }, null, 2));
  results.push([definition.kind, runtimeData(data)]);
}
const baked = Object.fromEntries(results);
const fields = results.map(([kind]) => `${kind}: BakedOrigami`).join('; ');
const source = `// Generated by npm run bake:origami. Do not edit by hand.
import type { BakedOrigami } from './data.js';

export const baked: { ${fields} } = ${JSON.stringify(baked)};
`;
writeFileSync(new URL('../src/game/origami/baked.ts', import.meta.url), source);
const directory = new URL('../.tmp/origami-preview/', import.meta.url);
mkdirSync(directory, { recursive: true });
writeFileSync(new URL('baked.json', directory), JSON.stringify(baked));
